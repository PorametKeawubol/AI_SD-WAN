"""SQL persistence in TimescaleDB; each live service/experiment has its own stream."""

import json
import os
import re
from contextlib import contextmanager
from datetime import UTC, datetime

import psycopg
from psycopg.rows import dict_row
from psycopg.types.json import Jsonb


class StorageError(RuntimeError):
    """Public error that does not expose a database URL or password."""


def json_value(value):
    return Jsonb(value, dumps=lambda row: json.dumps(row, allow_nan=False))


class Store:
    backend = "timescaledb"

    def __init__(self, database_url=None, *, stream="live"):
        self.database_url = database_url or os.getenv("SDWAN_DATABASE_URL")
        if not isinstance(self.database_url, str) or not self.database_url.startswith(
            ("postgresql://", "postgres://")
        ):
            raise StorageError("Configure SDWAN_DATABASE_URL for TimescaleDB")
        if not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9_.:-]{0,127}", stream):
            raise ValueError("Invalid database stream")
        self.stream = stream
        with self.connection() as connection:
            extension = connection.execute(
                "SELECT extversion FROM pg_extension WHERE extname='timescaledb'"
            ).fetchone()
            if not extension:
                raise StorageError("The configured database requires the TimescaleDB extension")
            self.version = extension["extversion"]
            connection.execute("""
                CREATE TABLE IF NOT EXISTS telemetry (
                    stream TEXT NOT NULL, link_id TEXT NOT NULL,
                    observed_at TIMESTAMPTZ NOT NULL, timestamp DOUBLE PRECISION NOT NULL,
                    up BOOLEAN NOT NULL, latency_ms DOUBLE PRECISION NOT NULL,
                    jitter_ms DOUBLE PRECISION NOT NULL, loss_pct DOUBLE PRECISION NOT NULL,
                    utilization_pct DOUBLE PRECISION NOT NULL, payload JSONB NOT NULL,
                    PRIMARY KEY (stream, link_id, observed_at)
                );
                SELECT create_hypertable('telemetry', 'observed_at',
                    if_not_exists => TRUE, chunk_time_interval => INTERVAL '1 day');
                CREATE INDEX IF NOT EXISTS telemetry_stream_link_time_idx ON telemetry(stream, link_id, observed_at DESC);
                CREATE TABLE IF NOT EXISTS events (
                    stream TEXT NOT NULL, id BIGINT GENERATED BY DEFAULT AS IDENTITY,
                    observed_at TIMESTAMPTZ NOT NULL, timestamp DOUBLE PRECISION NOT NULL,
                    kind TEXT NOT NULL, payload JSONB NOT NULL, PRIMARY KEY (stream, id)
                );
                CREATE INDEX IF NOT EXISTS events_stream_time_idx ON events(stream, id DESC);
                CREATE TABLE IF NOT EXISTS state (
                    stream TEXT NOT NULL, key TEXT NOT NULL, payload JSONB NOT NULL,
                    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(), PRIMARY KEY (stream, key)
                );
            """)

    @contextmanager
    def connection(self):
        try:
            with psycopg.connect(
                self.database_url,
                row_factory=dict_row,
                connect_timeout=5,
                options="-c timezone=UTC -c statement_timeout=15000",
            ) as connection:
                yield connection
        except psycopg.Error as error:
            raise StorageError("TimescaleDB operation failed: " + type(error).__name__) from None

    @staticmethod
    def telemetry_record(stream, sample):
        return (
            stream,
            sample.link_id,
            datetime.fromtimestamp(sample.timestamp, UTC),
            sample.timestamp,
            sample.up,
            sample.latency_ms,
            sample.jitter_ms,
            sample.loss_pct,
            sample.utilization_pct,
            json_value(sample.model_dump()),
        )

    def ingest(self, samples):
        with self.connection() as connection, connection.cursor() as cursor:
            cursor.executemany(
                "INSERT INTO telemetry VALUES (%s,%s,%s,%s,%s,%s,%s,%s,%s,%s)",
                [self.telemetry_record(self.stream, sample) for sample in samples],
            )

    def history(self, link_id, limit=12):
        with self.connection() as connection:
            rows = connection.execute(
                "SELECT payload FROM telemetry WHERE stream=%s AND link_id=%s ORDER BY observed_at DESC LIMIT %s",
                (self.stream, link_id, limit),
            ).fetchall()
        return [row["payload"] for row in reversed(rows)]

    def log(self, now, kind, payload):
        with self.connection() as connection:
            connection.execute(
                "INSERT INTO events(stream,observed_at,timestamp,kind,payload) VALUES (%s,%s,%s,%s,%s)",
                (
                    self.stream,
                    datetime.fromtimestamp(now, UTC),
                    now,
                    kind,
                    json_value(payload),
                ),
            )

    def events(self, limit=100):
        with self.connection() as connection:
            return connection.execute(
                "SELECT id,timestamp,kind,payload FROM events WHERE stream=%s ORDER BY id DESC LIMIT %s",
                (self.stream, limit),
            ).fetchall()

    def get(self, key, default=None):
        with self.connection() as connection:
            row = connection.execute(
                "SELECT payload FROM state WHERE stream=%s AND key=%s", (self.stream, key)
            ).fetchone()
        return row["payload"] if row else default

    def put(self, key, value):
        with self.connection() as connection:
            connection.execute(
                "INSERT INTO state(stream,key,payload) VALUES (%s,%s,%s) ON CONFLICT(stream,key) DO UPDATE SET payload=excluded.payload,updated_at=now()",
                (self.stream, key, json_value(value)),
            )

    def export(self):
        with self.connection() as connection:
            telemetry = connection.execute(
                "SELECT payload FROM telemetry WHERE stream=%s ORDER BY observed_at,link_id",
                (self.stream,),
            ).fetchall()
            events = connection.execute(
                "SELECT id,timestamp,kind,payload FROM events WHERE stream=%s ORDER BY id",
                (self.stream,),
            ).fetchall()
            state = connection.execute(
                "SELECT key,payload FROM state WHERE stream=%s ORDER BY key", (self.stream,)
            ).fetchall()
        return {
            "storage": self.backend,
            "stream": self.stream,
            "telemetry": [row["payload"] for row in telemetry],
            "events": events,
            "state": {row["key"]: row["payload"] for row in state},
        }
